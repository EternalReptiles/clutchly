// Builds the static support/legal site in /site from /site/_templates, filling in the app name from brand.json.
// Run after changing a template, help.json or the app name:  node scripts/build_site.mjs   (add --check to verify it's current)
// Host the /site folder anywhere static (Netlify, Vercel, GitHub Pages), then put its address in brand.json "siteUrl".
import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const brand = JSON.parse(fs.readFileSync(path.join(root, 'brand.json'), 'utf8'));
const tdir = path.join(root, 'site/_templates'); let stale = false;
const shell = (title, body) => `<!doctype html>
<html lang="en-AU"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title} · ${brand.name}</title><link rel="stylesheet" href="style.css"><link rel="icon" href="img/favicon.png">
<link rel="apple-touch-icon" href="/apple-touch-icon.png"><link rel="manifest" href="/site.webmanifest"><meta name="theme-color" content="#fcfcf8">
<meta name="apple-mobile-web-app-title" content="${brand.name}">
<meta name="description" content="${brand.name}: feeding, shed, weight and breeding records for reptile keepers and breeders."></head>
<body><header><a href="index.html" class="brand"><img src="img/logo.png" alt="" width="34" height="33">${brand.name}</a><nav><a href="app/">Web app</a><a href="support.html">Support</a><a href="privacy.html">Privacy</a><a href="terms.html">Terms</a></nav></header>
<main>${body.trim()}</main>
<footer>© ${brand.name} · <a href="app/">Web app</a> · <a href="support.html">Support</a> · <a href="privacy.html">Privacy</a> · <a href="terms.html">Terms</a></footer></body></html>
<!-- GENERATED by scripts/build_site.mjs from site/_templates. Edit the template, not this file. -->
`;
// The questions and answers from help.json (the same ones the app's Help screen shows): **bold**, blank-line paragraphs.
const esc = t => t.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
function faqHtml() {
  const help = JSON.parse(fs.readFileSync(path.join(root, 'help.json'), 'utf8'));
  const answer = a => a.split(/\n\s*\n/).map(p => `<p>${esc(p).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')}</p>`).join('\n');
  return help.sections.map(sec => `<h3 class="faq-section">${esc(sec.title)}</h3>\n` + sec.items.map(i => `<h4>${esc(i.q)}</h4>\n${answer(i.a)}`).join('\n')).join('\n\n');
}
for (const f of fs.readdirSync(tdir).filter(f => f.endsWith('.html'))) {
  const src = fs.readFileSync(path.join(tdir, f), 'utf8');
  const title = (src.match(/<!-- TITLE: (.+?) -->/) || [, 'Page'])[1];
  let body = src.replace(/<!-- TITLE: .+? -->/, '').replace('{{FAQ}}', faqHtml()).replaceAll('{{APP_NAME}}', brand.name).replaceAll('{{SUPPORT_EMAIL}}', brand.supportEmail);
  if (brand.supportEmail && !/\[/.test(brand.supportEmail)) body = body.replaceAll('[SUPPORT EMAIL]', brand.supportEmail); // filled once set in brand.json
  const out = shell(title, body);
  const dest = path.join(root, 'site', f);
  if (process.argv.includes('--check')) { if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) { console.error(`${f} is out of date`); stale = true; } }
  else { fs.writeFileSync(dest, out); console.log('wrote site/' + f); }
}
// site/js/labels.js: the app's label maker (lib/labels.ts) and its QR encoder for the browser, used by site/labels.html
// to print labels from the home-screen web app (iOS can't print from inside one, so it opens this page in Safari).
{
  const { createRequire } = await import('node:module'); const require = createRequire(import.meta.url);
  const ts = require('typescript');
  const qr = fs.readFileSync(path.join(root, 'node_modules/qrcode-generator/dist/qrcode.js'), 'utf8');
  const src = fs.readFileSync(path.join(root, 'lib/labels.ts'), 'utf8').replace(/^import .*$/gm, '');
  const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext } }).outputText
    .replace(/^export (function|const|async function)/gm, '$1').replace(/^export \{\s*\};?\s*$/gm, '');
  const out = `// GENERATED by scripts/build_site.mjs from lib/labels.ts and qrcode-generator. Do not edit.
(function () {
const brand = ${JSON.stringify({ name: brand.name, siteUrl: brand.siteUrl })};
${qr}
${js}
window.ClutchlyLabels = { labelsHtml, LAYOUTS, layoutOf };
})();
`;
  const dest = path.join(root, 'site/js/labels.js');
  if (process.argv.includes('--check')) { if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) { console.error('js/labels.js is out of date'); stale = true; } }
  else { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, out); console.log('wrote site/js/labels.js'); }
}
process.exit(stale ? 1 : 0);
